"""Prepare a validated Jekyll build for static-only Cloudflare Pages hosting."""

import argparse
import json
from pathlib import Path
from urllib.parse import urlsplit


def prepare(root):
    root = Path(root).resolve()
    if not (root / "404.html").is_file():
        raise ValueError("404.html is required to prevent SPA fallback for missing URLs")
    if (root / "_worker.js").exists() or (root / "functions").exists():
        raise ValueError("This deployment must contain only static files")
    files = [path for path in root.rglob("*") if path.is_file()]
    if len(files) + 1 > 20000:
        raise ValueError("The site exceeds the Cloudflare Pages Free file limit")
    for path in files:
        if path.is_symlink() or not path.resolve().is_relative_to(root):
            raise ValueError(f"Unsafe upload path: {path.relative_to(root)}")
        if path.stat().st_size > 25 * 1024 * 1024:
            raise ValueError(f"Asset exceeds 25 MiB: {path.relative_to(root)}")

    # Jekyll's HTML redirect pages remain in the build for GitHub rollback.
    # Use HTTP redirects on Pages, including its extensionless HTML aliases.
    redirects = json.loads((root / "redirects.json").read_text())
    rules = {}
    for source, destination in redirects.items():
        target = urlsplit(destination)
        if target.scheme != "https" or target.netloc != "chojecki.net" or target.query or target.fragment:
            raise ValueError(f"Unexpected redirect destination for {source}")
        if not source.startswith("/") or any(c.isspace() for c in source + target.path):
            raise ValueError("Invalid redirect path")
        aliases = {source}
        if source.endswith(".html"):
            aliases.add(source[:-5])
        elif source.endswith("/"):
            aliases.add(source.rstrip("/"))
        for alias in sorted(aliases):
            if alias and alias != target.path:
                if alias in rules and rules[alias] != target.path:
                    raise ValueError(f"Conflicting redirect: {alias}")
                rules[alias] = target.path
    # Hostname redirects belong in Cloudflare zone Redirect Rules; Pages'
    # _redirects file supports path redirects only.
    lines = ["# Generated by scripts/prepare-cloudflare.py; do not edit in _site."]
    lines.extend(f"{source} {destination} 301" for source, destination in sorted(rules.items()))
    if len(rules) > 2000:
        raise ValueError("Too many static redirect rules")
    (root / "_redirects").write_text("\n".join(lines) + "\n")
    print(f"Cloudflare upload ready: {len(files)} files, {len(rules)} legacy redirects, static-only hosting.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("site_dir", nargs="?", default="_site", type=Path)
    args = parser.parse_args()
    prepare(args.site_dir)
