"""Content-addressed rendering assets and Pages response headers."""

import hashlib
import re
from pathlib import Path
from urllib.parse import urljoin, urlsplit

IMMUTABLE = "public, max-age=31536000, immutable"
FINGERPRINT = re.compile(r"\.[0-9a-f]{16}(?=\.[^.]+$)")
CSS_URL = re.compile(r"url\(\s*(['\"]?)([^)'\"]+)\1\s*\)")
HTML_ASSET = re.compile(
    r"(?P<quote>['\"])(?:https://chojecki\.net)?"
    r"(?P<path>/assets/(?:css|js|webfonts)/[^'\"?#\s]+)"
    r"(?:\?[^'\"#]*)?(?P<fragment>\#[^'\"]*)?(?P=quote)"
)


def fingerprinted(path, content):
    digest = hashlib.sha256(content).hexdigest()[:16]
    return path.with_name(f"{path.stem}.{digest}{path.suffix}")


def optimize(root):
    """Keep original URLs while making rendered resources safe to cache long-term."""
    root = Path(root).resolve()
    sources = [root / "assets/js" / name for name in
               ("main.min.js", "theme-toggle.js", "site-delight.js")]
    sources += [p for p in sorted((root / "assets/webfonts").glob("*"))
                if p.suffix in {".woff2", ".ttf"} and not FINGERPRINT.search(p.name)]
    css = root / "assets/css/main.css"
    mapping = {}

    def publish(source, content):
        target = fingerprinted(source, content)
        if source.is_symlink() or target.is_symlink() or not source.resolve().is_relative_to(root) or not target.resolve().is_relative_to(root):
            raise ValueError("Unsafe rendering asset path")
        target.write_bytes(content)
        mapping["/" + source.relative_to(root).as_posix()] = "/" + target.relative_to(root).as_posix()

    for source in sources:
        if not source.is_file():
            raise ValueError(f"Missing rendering asset: {source.relative_to(root)}")
        publish(source, source.read_bytes())

    def css_reference(match):
        reference = match[2].strip()
        url = urlsplit(urljoin("https://chojecki.net/assets/css/main.css", reference))
        if url.scheme not in {"http", "https"} or url.netloc != "chojecki.net":
            return match[0]
        target = (root / url.path.lstrip("/")).resolve()
        if not target.is_relative_to(root) or not target.is_file():
            raise ValueError(f"Missing or unsafe CSS resource: {url.path}")
        replacement = mapping.get(url.path)
        if not replacement:
            return match[0]
        if url.fragment:
            replacement += "#" + url.fragment
        return f'url("{replacement}")'

    publish(css, CSS_URL.sub(css_reference, css.read_text()).encode())
    stylesheet = mapping["/assets/css/main.css"]
    hints = []

    def html_reference(match):
        # Also support repeating preparation in an existing build directory.
        original = FINGERPRINT.sub("", match["path"])
        target = mapping.get(original)
        if not target:
            return match[0]
        return match["quote"] + target + (match["fragment"] or "") + match["quote"]

    for page in sorted(root.rglob("*.html")):
        text = HTML_ASSET.sub(html_reference, page.read_text())
        page.write_text(text)
        if stylesheet in text:
            relative = page.relative_to(root).as_posix()
            route = "/" + (relative[:-10] if relative.endswith("index.html") else relative.removesuffix(".html"))
            hints.append(route)

    headers = ["# Generated by scripts/cloudflare_assets.py; do not edit in _site."]
    for target in sorted(mapping.values()):
        headers.extend([target, f"  Cache-Control: {IMMUTABLE}", ""])
    for route in hints:
        headers.extend([route, f"  Link: <{stylesheet}>; rel=preload; as=style", ""])
    if len(mapping) + len(hints) > 100:
        raise ValueError("The site exceeds the Pages header-rule limit")
    if any(len(line) > 2000 for line in headers):
        raise ValueError("The site exceeds the Pages header-line limit")
    (root / "_headers").write_text("\n".join(headers) + "\n")
    return mapping


def header_rules(root):
    """Read the exact-path header rules generated for this build."""
    rules = {}
    current = None
    for line in (Path(root) / "_headers").read_text().splitlines():
        if line.startswith("/"):
            current = line
            rules[current] = {}
        elif line.startswith("  ") and current:
            key, value = line.strip().split(":", 1)
            rules[current][key.lower()] = value.strip()
    return rules
